#!/usr/bin/env python3
"""
Azure DevOps Ticket Quality Analyzer
Generates quality reports for work items and saves them to markdown.
"""

import os
import json
import sys
from pathlib import Path
from datetime import datetime


def create_documents_dir():
    """Ensure the documents directory exists."""
    docs_dir = Path("documents")
    docs_dir.mkdir(exist_ok=True)
    return docs_dir


def save_report(ticket_id: str, report_content: str, analysis: dict) -> tuple:
    """Save the quality report to both markdown and JSON files."""
    docs_dir = create_documents_dir()

    # Save markdown
    md_filename = f"ticket-quality-{ticket_id}.md"
    md_filepath = docs_dir / md_filename
    with open(md_filepath, 'w', encoding='utf-8') as f:
        f.write(report_content)

    # Save JSON
    json_filename = f"ticket-quality-{ticket_id}.json"
    json_filepath = docs_dir / json_filename
    with open(json_filepath, 'w', encoding='utf-8') as f:
        json.dump(analysis, f, indent=2, ensure_ascii=False)

    return str(md_filepath), str(json_filepath)


def format_report(analysis: dict, ticket_id: str, ticket_title: str) -> str:
    """Format the analysis into a markdown report."""
    report = f"""# Ticket Quality Report: {ticket_title}

**Ticket ID:** {ticket_id}
**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Quality Score: {analysis.get('overall_score', 'N/A')}/100

### Criterion Breakdown
"""

    if 'criteria' in analysis:
        for criterion, score_data in analysis['criteria'].items():
            score = score_data.get('score', 'N/A')
            weight = score_data.get('weight', 'N/A')
            report += f"- **{criterion}**: {score}/100 (weight: {weight})\n"

    report += "\n## Strengths\n"
    if 'strengths' in analysis:
        for strength in analysis['strengths']:
            report += f"✔ {strength}\n"
    else:
        report += "- No strengths identified\n"

    report += "\n## Weaknesses\n"
    if 'weaknesses' in analysis:
        for weakness in analysis['weaknesses']:
            report += f"✖ {weakness}\n"
    else:
        report += "- No significant weaknesses\n"

    report += "\n## Red Flags\n"
    if 'red_flags' in analysis:
        for flag in analysis['red_flags']:
            report += f"⚠ {flag}\n"
    else:
        report += "- No red flags detected\n"

    report += "\n## Suggested Questions\n"
    if 'suggested_questions' in analysis:
        for i, question in enumerate(analysis['suggested_questions'], 1):
            report += f"{i}. {question}\n"
    else:
        report += "- No follow-up questions\n"

    report += "\n## Recommendations\n"
    if 'recommendations' in analysis:
        for rec in analysis['recommendations']:
            report += f"- {rec}\n"
    else:
        report += "- No recommendations at this time\n"

    report += f"\n---\n*Report generated by Azure DevOps Ticket Quality Analyzer*\n"

    return report


def main():
    """Main entry point for the analyzer."""
    if len(sys.argv) < 2:
        print("Usage: analyzer.py <ticket_id> [analysis_json_file]", file=sys.stderr)
        sys.exit(1)

    ticket_id = sys.argv[1]

    # Try to read analysis from stdin or file
    if len(sys.argv) > 2:
        with open(sys.argv[2], 'r') as f:
            analysis = json.load(f)
    else:
        # Read from stdin
        analysis = json.load(sys.stdin)

    ticket_title = analysis.get('ticket_title', f'Work Item {ticket_id}')

    # Format and save the report
    report_content = format_report(analysis, ticket_id, ticket_title)
    md_filepath, json_filepath = save_report(ticket_id, report_content, analysis)

    print(f"✓ Markdown report saved to: {md_filepath}")
    print(f"✓ JSON report saved to: {json_filepath}")
    print("\nReport Preview:")
    print(report_content)


if __name__ == '__main__':
    main()
